package Skillbuilders;

public class RectanglePerimeter {
	
	public static void main(String[] args) {
		int length = 13;
		int width = 4;
		int perimeter;
		
		perimeter = 2 *length + 2 * width;
		System.out.println("Perimeter of Rectangle with length (13) and width (4): " + perimeter);

}
}